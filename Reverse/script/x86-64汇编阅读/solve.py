# asm 汇编分支还原脚本
# 原理：先原样复制 byte_404000 的 19 字节；分支判断恒真，实际走到 XOR 分支，
#       把 byte_404020 的 31 字节逐个与 0x42 异或；byte_404030 是干扰分支，不执行。

prefix = [0x66, 0x6c, 0x61, 0x67, 0x7b, 0x55, 0x6e, 0x64, 0x65, 0x72,
          0x73, 0x74, 0x61, 0x6e, 0x64, 0x69, 0x6e, 0x67, 0x5f]

cipher = [0x23, 0x31, 0x31, 0x27, 0x2f, 0x20, 0x2e, 0x3b, 0x1d, 0x2e,
          0x23, 0x2c, 0x25, 0x37, 0x23, 0x25, 0x27, 0x1d, 0x2b, 0x31,
          0x1d, 0x2b, 0x2f, 0x32, 0x2d, 0x30, 0x36, 0x23, 0x2c, 0x36,
          0x3f]

decoy = [0x63, 0x6f, 0x72, 0x72, 0x65, 0x63, 0x74, 0x21, 0x7d]  # 干扰分支，不拼接

part1 = ''.join(chr(b) for b in prefix)
part2 = ''.join(chr(b ^ 0x42) for b in cipher)

print("flag =", part1 + part2)
