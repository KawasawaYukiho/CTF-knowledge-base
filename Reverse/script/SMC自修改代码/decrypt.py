# SMC 自修改代码解密脚本
# 原理：SMC 解密 stub 用 VirtualProtect 把 .text 段 0x401080 起的 4KB 改成可写，
#       再把该地址起的 36 个字节逐个 XOR 0x90 写回原地址。
#       本脚本手动模拟这个过程，把加密字节还原成真实机器码，再反汇编即可看到校验逻辑。

enc = [0xC5, 0x1B, 0x7C, 0xC1, 0x11, 0xED, 0x98, 0xA9, 0xA0, 0x90,
       0x90, 0xE5, 0x99, 0x57, 0xD5, 0x6C, 0x91, 0x90, 0x90, 0x90,
       0x7B, 0x97, 0x57, 0xD5, 0x6C, 0x90, 0x90, 0x90, 0x90, 0x1B,
       0xD5, 0x6C, 0x1B, 0x75, 0xCD, 0x53]

dec = [b ^ 0x90 for b in enc]
print("decrypted bytes:", ' '.join('%02X' % b for b in dec))

